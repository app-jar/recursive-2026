% Условие задачи (Вариант 19): Получить НОД и НОК списка чисел.
% Вход: список целых положительных чисел. Пример: [12, 18, 30]. Результат: НОД = 6, НОК = 180.

% --- Базовые предикаты для двух чисел ---

% Предикат для нахождения НОД (Наибольший общий делитель) двух чисел (алгоритм Евклида)
gcd(A, 0, A) :- !.
gcd(A, B, G) :-
    B > 0,
    R is A mod B,
    gcd(B, R, G).

% Предикат для нахождения НОК (Наименьшее общее кратное) двух чисел
% Формула: НОК(A, B) = (A * B) / НОД(A, B)
lcm(A, B, L) :-
    gcd(A, B, G),
    L is (A * B) // G.

% --- Обработка списков ---

% Предикат для нахождения НОД всего списка
gcd_list([X], X) :- !. % Базовый случай: НОД одного элемента — это сам элемент
gcd_list([H|T], G) :-
    gcd_list(T, G_Tail), % Рекурсивно находим НОД хвоста списка
    gcd(H, G_Tail, G).   % Находим НОД текущего элемента и НОД хвоста

% Предикат для нахождения НОК всего списка
lcm_list([X], X) :- !. % Базовый случай: НОК одного элемента — это сам элемент
lcm_list([H|T], L) :-
    lcm_list(T, L_Tail), % Рекурсивно находим НОК хвоста списка
    lcm(H, L_Tail, L).   % Находим НОК текущего элемента и НОК хвоста

% --- Главный предикат ---

% Вычисляет одновременно НОД и НОК для заданного списка
% Использование: list_gcd_lcm([12, 18, 30], GCD, LCM).
list_gcd_lcm(List, GCD, LCM) :-
    gcd_list(List, GCD),
    lcm_list(List, LCM).