% Условие: Сгенерировать список, содержащий первые N членов арифметической прогрессии.
% Вход: первый член прогрессии A, разность D и количество членов N.
% Пример: A = 3, D = 4, N = 5. Результат: [3, 7, 11, 15, 19].

% generate_ap(A, D, N, Result)
% Базовый случай: если осталось сгенерировать 0 элементов, возвращаем пустой список
generate_ap(_, _, 0, []) :- !.

% Рекурсивный случай: для N > 0 фиксируем текущий элемент A
% и вычисляем следующий элемент (A + D) и новый счетчик (N - 1)
generate_ap(A, D, N, [A | Rest]) :-
    N > 0,
    NextA is A + D,
    NextN is N - 1,
    generate_ap(NextA, D, NextN, Rest).
