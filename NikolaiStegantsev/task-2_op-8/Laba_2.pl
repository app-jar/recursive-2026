% Проверить, является ли бинарное дерево строгим: каждый узел имеет либо двух потомков, либо ни одного.

% Проверка, что оба поддерева одновременно отсутствуют или одновременно присутствуют
both_nil(nil, nil).
both_nil(L, R) :-
    L \= nil,
    R \= nil.

% Пустое дерево считается строгим
op8(nil).

% Узел строгий, если детей либо двое, либо ноль, и оба поддерева строгие
op8(node(_, L, R)) :-
    both_nil(L, R),
    op8(L),
    op8(R).

% Тесты:
% op8(node(1,node(2,nil,nil),node(3,nil,nil))).
%     ответ: Да
% op8(node(1,node(2,nil,nil),nil)).
