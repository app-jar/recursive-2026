% Базовый случай: список из одного элемента (или пустой) всегда истина.
check_ap([_], _).
check_ap([], _).

% Рекурсивный случай: проверяем разность первых двух и идем дальше.
check_ap([H1, H2 | T], K) :-
    H2 =:= H1 + K,
    check_ap([H2 | T], K).
