% op8(node(1,nil,node(3,nil,nil))).
%     ответ: Нет
% op8(node(1,node(2,node(4,nil,nil),node(5,nil,nil)),node(3,nil,nil))).
%     ответ: Да
% op8(node(1,node(2,node(4,nil,nil),nil),node(3,nil,nil))).
%     ответ: Нет
% op8(node(1,nil,nil)).
