Проверить, является ли указанное число корнем многочлена.
Вход: список коэффициентов многочлена и число X. Коэффициенты задаются от коэффициента при старшей степени к свободному члену.
Пример: для многочлена 2x3 - 3x2 - 8x + 12 входными данными являются [2, -3, -8, 12] и X = 2.
Результат: да, поскольку значение многочлена в точке 2 равно 0.
*/

/*Вычисление многочлена по схеме Горнера с накоплением результата и проходом слева направа*/
eval_poly([], _, Acc, Acc).
eval_poly([H|T], X, Acc, Result) :-
    Acc1 is Acc * X + H,
    eval_poly(T, X, Acc1, Result).

is_root([], _) :- fail. /*Обработка пустого списка кэффициентов*/

is_root(Coeffs, X) :- /*Проверка на корень, начальное значение для накопления 0*/
    eval_poly(Coeffs, X, 0, Value),
    Value =:= 0.
/*
Сoeffs - список с коэффициентами
X - корень
*/

/*
Пример для тестирования задачи:
is_root([2, -3, -8, 12], 2).

