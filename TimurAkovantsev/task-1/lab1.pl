/*Проверка наличия делителя числа X в диапазоне от D до sqrt(X)*/
has_divisor(X, D) :-
    D * D =< X,
    X mod D =:= 0, !.
has_divisor(X, D) :-
    D * D =< X,
    D1 is D + 1,
    has_divisor(X, D1).

/*Число X является простым, если X >= 2 и не имеет делителей, начиная с 2*/
is_prime(X) :-
    X >= 2,
    \+ has_divisor(X, 2).

/*Базис рекурсии: если текущее число превысило N, возвращаем пустой список*/
primes_from(Current, N, []) :-
    Current > N, !.

/*Шаг рекурсии 1: число Current простое — добавляем его в голову списка [Current|Rest]*/
primes_from(Current, N, [Current|Rest]) :-
    is_prime(Current), !,
    Next is Current + 1,
    primes_from(Next, N, Rest).

/*Шаг рекурсии 2: число Current составное — пропускаем его и идем дальше*/
primes_from(Current, N, Rest) :-
    Next is Current + 1,
    primes_from(Next, N, Rest).

primes(N, _) :- N < 1, !, fail. /*Обработка некорректного входного значения (N должно быть положительным) с отсечением*/

primes(N, Result) :- /*Поиск простых чисел, начиная с первого простого числа (2)*/
    primes_from(2, N, Result).
/*
N - целое положительное число (верхняя граница)
Result - список простых чисел, не превышающих N
*/

