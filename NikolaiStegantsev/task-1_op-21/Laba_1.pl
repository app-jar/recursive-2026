% Стеганцев Николай 9 группа
% Лабораторная 1,
% Задача 21.
% Получить список разностей соседних элементов исходного списка.
% Для каждой пары соседних элементов вычисляется следующий - предыдущий.

op21([], []).
op21([_], []).
op21([X, Y | T], [D | R]) :-
    D is Y - X,
    op21([Y | T], R).

% Тесты:
% op21([5, 8, 4, 10], R).
%     ответ: [3, -4, 6]
% op21([1, 2, 3, 4], R).
%     ответ: [1, 1, 1]
% op21([10, 5, 1], R).
%     ответ: [-5, -4]
% op21([7], R).
%     ответ: []
% op21([], R).
%     ответ: []
% op21([3, 3, 3, 3], R).
%     ответ: [0, 0, 0]