/*
Гурьева Полина 9 группа
Лабораторная № 1 задача 24

Условие:
Проверить, что каждый следующий элемент списка больше предыдущего ровно на заданное число К.

Примеры тестов для запуска вручную:
check_ap([3, 7, 11, 15], 4).      % true (обычная)
check_ap([10, 8, 6, 4], -2).      % true (убывающая)
check_ap([5, 5, 5, 5], 0).        % true (K = 0)
check_ap([1, 3, 2], 2).           % false
check_ap([], 5).                  % true (пустой список)
check_ap([5], 5).                 % true (один элемент)
*/

% Базовый случай: пустой список или список из одного элемента всегда истина
check_ap([], _).
check_ap([_], _).

% Рекурсивный случай: проверяем разность первых двух и идем дальше
check_ap([H1, H2 | T], K) :-
    H2 =:= H1 + K,
    check_ap([H2 | T], K).
