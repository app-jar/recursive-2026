% Проверить, является ли список фрагментом другого списка.
% Фрагмент должен состоять из последовательных элементов второго списка.
% Пример: [3, 4, 5] и [1, 2, 3, 4, 5, 6].
% Результат: да.

is_fragment(Fragment, List) :-
    append(_, Rest, List),
    append(Fragment, _, Rest).

