% Лабораторная работа 1
% Вход: список элементов. Первый и второй элементы меняются местами, затем третий и
% четвёртый и т. д.

swap_pairs([], []).
swap_pairs([X], [X]).
swap_pairs([X, Y | T], [Y, X | R]) :-
    swap_pairs(T, R).

% ---------------------------------------------------------------
% Примеры тестов
% ---------------------------------------------------------------

% 1. Пример из задания (нечётная длина):
% swap_pairs([1, 2, 3, 4, 5], X).
% X = [2, 1, 4, 3, 5].

% 2. Чётная длина:
% swap_pairs([1, 2, 3, 4], X).
% X = [2, 1, 4, 3].

% 3. Пустой список:
% swap_pairs([], X).
% X = [].

% 4. Один элемент:
% swap_pairs([a], X).
% X = [a].

% 5. Два элемента:
% swap_pairs([a, b], X).
% X = [b, a].

% 6. Три элемента:
% swap_pairs([a, b, c], X).
% X = [b, a, c].

% 7. Элементы разных типов:
% swap_pairs([1, a, "str", f(x), 2.5, [y]], X).
% X = [a, 1, f(x), "str", [y], 2.5].

% 8. Повторяющиеся элементы:
% swap_pairs([x, x, y, y, z], X).
% X = [x, x, y, y, z].
