% Условие: Проверить, являются ли два списка перестановками друг друга.

% Два списка являются перестановками, если содержат одинаковые элементы с одинаковой
% кратностью, но элементы могут находиться в разном порядке.


% Удаляет одно вхождение элемента X из списка L.
% Если X встречается несколько раз, удаляется первое вхождение.
remove_one(X, [X|T], T) :- !.
remove_one(X, [H|T], [H|T1]) :-
    remove_one(X, T, T1).

% Проверка: L1 и L2 — перестановки друг друга.
are_permutations([], []).
are_permutations([X|Xs], L2) :-
    remove_one(X, L2, L2Rest),
    are_permutations(Xs, L2Rest).