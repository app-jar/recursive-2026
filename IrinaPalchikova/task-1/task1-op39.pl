% Найти все локальные максимумы списка.

local_max([A, B, C | T], [B | R]) :-
    B > A,
    B > C, !,
    local_max([B, C | T], R).

local_max([_, B, C | T], R) :-
    local_max([B, C | T], R).

local_max(_, []).

